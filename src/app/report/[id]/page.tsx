import { notFound } from "next/navigation";
import { headers } from "next/headers";
import { waitUntil } from "@vercel/functions";
import { findById, findOne, appendRow, updateById, Tables } from "@/lib/db";
import { generateReport } from "@/lib/report-generator";
import { sendReportPdfEmail } from "@/lib/email-pdf-pipeline";
import type { ParsedPolicy, PolicyReport } from "@/lib/types";
import { ReportDisplay } from "@/components/report-display";
import { getSession } from "@/lib/session";
import { getUploadSession } from "@/lib/upload-session";

// Allow up to 60s for on-demand report generation if it wasn't pre-generated
export const maxDuration = 60;

interface PageProps {
  params: Promise<{ id: string }>;
  searchParams: Promise<{
    from?: string;
    demo?: string;
    print?: string;
    km?: string;
    drv?: string;
    oc?: string;
    pri?: string;
    /** pastClaims — captured by MidLoadQuestions during parsing. */
    pc?: string;
  }>;
}

/** Resolve the request origin so puppeteer (running in a background
 *  waitUntil) knows where to fetch the report page from. Honours
 *  x-forwarded-* headers that Vercel injects; falls back to the
 *  configured public site URL. */
async function resolveBaseUrl(): Promise<string> {
  const hdrs = await headers();
  const proto = hdrs.get("x-forwarded-proto") ?? "https";
  const host =
    hdrs.get("x-forwarded-host") ??
    hdrs.get("host") ??
    process.env.NEXT_PUBLIC_SITE_URL ??
    "rightoffer.in";
  return `${proto}://${host}`;
}

export default async function ReportPage({ params, searchParams }: PageProps) {
  const [{ id }, sp] = await Promise.all([params, searchParams]);
  const { from, demo, print, km, drv, oc, pri, pc } = sp;
  const view: "investor" | "customer" = demo === "1" ? "investor" : "customer";
  const printMode = print === "1";

  const drivingProfile =
    km || drv || oc || pri || pc
      ? {
          annualKm: km,
          drivenBy: drv,
          otherCars: oc,
          priority: pri,
          pastClaims: pc,
        }
      : undefined;

  const parsedPolicy = await findById<ParsedPolicy>(
    Tables.PARSED_POLICIES,
    id
  );
  if (!parsedPolicy) notFound();

  let report = await findOne<PolicyReport>(
    Tables.REPORTS,
    (r) => r.parsedPolicyId === id
  );

  if (!report) {
    // First visit and report wasn't pre-generated by /api/parse (or generation failed).
    // Generate now and persist.
    console.log(`[report] No cached report for policy ${id}, generating...`);
    const start = Date.now();
    report = await generateReport(parsedPolicy);
    console.log(`[report] Generated in ${Date.now() - start}ms`);
    await appendRow<PolicyReport>(Tables.REPORTS, report);
  }

  // Minimum hold on the editorial loading page. Without this, customers
  // whose report is pre-generated see loading.tsx flash for a fraction
  // of a second — they feel they "missed something." We enforce a 6s
  // floor from the journey-start timestamp (passed in via `?from=`)
  // so every customer gets a paced "we're personalising for you" beat
  // before the report appears.
  //
  // If the server already took longer than 6s (e.g. on-demand report
  // generation), no extra hold — the loading.tsx already filled the
  // time naturally.
  const MIN_HOLD_MS = 6_000;
  if (from) {
    const journeyStart = parseInt(from, 10);
    if (Number.isFinite(journeyStart) && journeyStart > 0) {
      const elapsed = Date.now() - journeyStart;
      const remaining = MIN_HOLD_MS - elapsed;
      if (remaining > 0) {
        await new Promise((r) => setTimeout(r, remaining));
      }
    }
  }

  // Right Offer gate: customers who haven't verified their email yet
  // see the report up to the "what's missing" section, then a hard
  // gate. Investor + print mode skip the gate entirely. Customers
  // who hold either a full magic-link session OR an upload session
  // (OTP-verified email) bypass the gate too.
  const [fullSessionEmail, uploadSession] = await Promise.all([
    getSession(),
    getUploadSession(),
  ]);
  const hasVerifiedSession = !!(fullSessionEmail || uploadSession);
  const showGate = view === "customer" && !printMode && !hasVerifiedSession;

  // Auto-deliver the PDF to the customer's inbox on their first
  // verified visit. The customer just verified themselves (via OTP
  // or OAuth) — emailing them a copy of the audit is what the gate
  // promised when they handed over their email.
  //
  // Idempotent: we keep a list of emails we've already delivered to
  // on the report (`emailsSent`). If the customer's verified email
  // is already in the list, we skip. We mark BEFORE firing so a
  // page refresh during the puppeteer render doesn't trigger a
  // second send.
  //
  // Gated to view=customer + non-print so investor / PDF-render
  // paths don't accidentally fan out emails.
  const verifiedEmail =
    fullSessionEmail ?? uploadSession?.email ?? null;
  if (
    verifiedEmail &&
    view === "customer" &&
    !printMode &&
    !hasEmailBeenSent(report, verifiedEmail)
  ) {
    const updatedSent = [
      ...(report.emailsSent ?? []),
      verifiedEmail.toLowerCase(),
    ];
    // Mark synchronously so refreshes during the puppeteer render
    // don't re-fire. Best-effort — DB failure here is non-fatal.
    try {
      await updateById<PolicyReport>(Tables.REPORTS, report.id, {
        emailsSent: updatedSent,
      });
      report.emailsSent = updatedSent;
    } catch (err) {
      console.error("[report] Failed to mark email sent:", err);
    }
    // Fire the pipeline in the background; the customer's HTML
    // response ships immediately while puppeteer + Resend run.
    const baseUrl = await resolveBaseUrl();
    waitUntil(
      sendReportPdfEmail({
        reportId: parsedPolicy.id,
        email: verifiedEmail,
        baseUrl,
        query: { km, drv, oc, pri, pc },
      })
    );
  }

  return (
    <ReportDisplay
      parsedPolicy={parsedPolicy}
      report={report}
      view={view}
      showGate={showGate}
      drivingProfile={drivingProfile}
      printMode={printMode}
    />
  );
}

/** Has this email already been sent the PDF for this report? */
function hasEmailBeenSent(report: PolicyReport, email: string): boolean {
  const lowered = email.toLowerCase();
  return (report.emailsSent ?? []).some(
    (e) => e.toLowerCase() === lowered
  );
}
